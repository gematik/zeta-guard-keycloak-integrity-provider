package de.spree.keycloak.commons

import jakarta.persistence.EntityManager

/**
 * Abstract base class that provides Hibernate [org.hibernate.Session]-aware functionality, including access to the EntityManager.
 *
 * Subclasses can use the injected EntityManager for database operations.
 */
abstract class AbstractDao(private val entityManager: EntityManager) {
	protected open fun em(): EntityManager = entityManager
}
